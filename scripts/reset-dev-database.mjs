import { config as loadEnv } from "dotenv";
import postgres from "postgres";
import { spawnSync } from "node:child_process";
import { resolve } from "node:path";

loadEnv({ path: resolve("apps/api/.env"), override: false, quiet: true });
if (process.env.CONFIRM_DEV_DATABASE_RESET !== "YES") throw new Error("Reset refusé : définissez CONFIRM_DEV_DATABASE_RESET=YES.");
if (process.env.NODE_ENV === "production") throw new Error("Reset refusé : NODE_ENV=production.");
const raw = process.env.DATABASE_URL;
if (!raw) throw new Error("Reset refusé : DATABASE_URL est absente.");
const url = new URL(raw);
if (!["127.0.0.1", "localhost", "::1"].includes(url.hostname)) throw new Error(`Reset refusé : l’hôte ${url.hostname} n’est pas local.`);
const database = decodeURIComponent(url.pathname.slice(1));
if (!database || ["postgres", "template0", "template1"].includes(database)) throw new Error(`Reset refusé : base protégée « ${database} ».`);
console.log(`Reset développement autorisé — hôte: ${url.hostname}, base: ${database}`);
const sql = postgres(raw, { max: 1 });
await sql.unsafe("drop schema if exists public cascade");
await sql.unsafe("drop schema if exists drizzle cascade");
await sql.unsafe("create schema public");
await sql.end();
const migration = spawnSync(process.platform === "win32" ? "npm.cmd" : "npm", ["run", "db:migrate"], { cwd: process.cwd(), stdio: "inherit", env: process.env });
if (migration.status !== 0) throw new Error("Les migrations ont échoué après le reset.");
const verify = postgres(raw, { max: 1 });
const [{ users }] = await verify`select count(*)::int as users from users`;
const [{ tables }] = await verify`select count(*)::int as tables from information_schema.tables where table_schema='public'`;
const [{ migrations }] = await verify`select count(*)::int as migrations from drizzle.__drizzle_migrations`;
await verify.end();
if (users !== 0 || tables < 1 || migrations < 1) throw new Error("Vérification post-reset invalide.");
console.log(`Reset vérifié — utilisateurs: ${users}, tables: ${tables}, migrations: ${migrations}.`);
